/**
 * Compiles the Svelte email templates to plain server-side JavaScript (TECH_STACK §2,
 * packages/emails). The engine Worker is bundled by wrangler (esbuild), which can't load
 * `.svelte` files, so the compiled output is committed in src/generated and a test
 * (generated.test.ts) fails when it is out of date. Run `pnpm --filter @claimsale/emails
 * generate` after changing a template or upgrading Svelte.
 */
import { readdirSync, readFileSync } from "node:fs";
import { basename, join } from "node:path";
import { compile } from "svelte/compiler";

export const templatesDir = join(import.meta.dirname, "../src/templates");
export const generatedDir = join(import.meta.dirname, "../src/generated");

const HEADER = "// Generated by packages/emails/scripts/generate.ts from src/templates. Do not edit.\n";

/** Every generated file, by name: `<Name>.js` and `<Name>.d.ts` per template. */
export function compileTemplates(): Map<string, string> {
	const out = new Map<string, string>();
	for (const file of readdirSync(templatesDir)
		.filter((f) => f.endsWith(".svelte"))
		.toSorted()) {
		const name = basename(file, ".svelte");
		const source = readFileSync(join(templatesDir, file), "utf8");
		const { js } = compile(source, { generate: "server", filename: file, dev: false });
		// Templates import each other as `./X.svelte`; the generated modules sit side by side.
		const code = js.code.replace(/from (["'])\.\/(\w+)\.svelte\1/g, "from $1./$2.js$1");
		out.set(`${name}.js`, `${HEADER}${code}\n`);
		out.set(
			`${name}.d.ts`,
			`${HEADER}import type { Component } from "svelte";\nimport type { ${name}Props } from "../types.ts";\n\ndeclare const ${name}: Component<${name}Props>;\nexport default ${name};\n`,
		);
	}
	return out;
}
