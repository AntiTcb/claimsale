<article class="mx-auto max-w-2xl px-4 py-8">
	<h1 class="text-2xl font-bold tracking-tight">Prohibited items</h1>
	<p class="mt-4">
		ClaimSale is for trading card games: singles, graded cards, sealed product, TCG accessories and lots.
		Anything else doesn't belong here.
	</p>

	<h2 class="mt-8 text-lg font-semibold">Never allowed</h2>
	<ul class="mt-2 list-disc space-y-1 pl-6">
		<li>Proxies, counterfeits and orica.</li>
		<li>"Replica" or custom cards that imitate real cards.</li>
		<li>Digital code cards: PTCGL, Arena or any other redeemable code.</li>
		<li>Items that aren't trading card game products.</li>
	</ul>

	<h2 class="mt-8 text-lg font-semibold">Allowed with a label</h2>
	<ul class="mt-2 list-disc space-y-1 pl-6">
		<li>Altered art, marked as altered.</li>
		<li>Repacks, labelled "repack, not factory sealed".</li>
	</ul>

	<h2 class="mt-8 text-lg font-semibold">Photos</h2>
	<p class="mt-2">
		Every item needs its own photo, taken by the seller. A photo that matches another seller's image is
		rejected, and newer sellers add a timestamp photo to each sale.
	</p>

	<h2 class="mt-8 text-lg font-semibold">If you see one</h2>
	<p class="mt-2">
		Use "Report" on the sale or the seller's profile. An admin reviews every report, and listings that break
		these rules are removed; repeat offenders lose their account.
	</p>
</article>
